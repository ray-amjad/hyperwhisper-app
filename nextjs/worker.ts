/**
 * The Worker entry (wrangler.jsonc `main`). It wraps the handler OpenNext
 * generates in `.open-next/worker.js` and adds what Vercel used to provide:
 *
 * - `scheduled()`: the cron triggers in wrangler.jsonc. Each one calls its
 *   internal prune route (config/cron-jobs.mjs) through the Next handler with
 *   `Authorization: Bearer $CRON_SECRET`, the same request Vercel cron sent.
 * - uncompressed docs for a client that sent no Accept-Encoding: the
 *   Mintlify rewrite passes Mintlify's Content-Encoding through.
 * - the Durable Object classes OpenNext's ISR queue and tag cache need.
 *
 * Excluded from tsconfig: `.open-next/worker.js` exists only after
 * `opennextjs-cloudflare build`.
 */
// @ts-ignore generated by `opennextjs-cloudflare build`
import { default as handler } from "./.open-next/worker.js";
import { CRON_JOBS } from "./config/cron-jobs.mjs";
import { withAcceptedEncoding } from "./lib/cloudflare/content-encoding";

// @ts-ignore generated by `opennextjs-cloudflare build`
export { DOQueueHandler, DOShardedTagCache } from "./.open-next/worker.js";

type Env = { CRON_SECRET?: string } & Record<string, unknown>;
type Ctx = { waitUntil(promise: Promise<unknown>): void };

export default {
  async fetch(request: Request, env: Env, ctx: Ctx): Promise<Response> {
    // Proxied Mintlify responses keep Mintlify's Content-Encoding; drop it
    // when the client cannot decode it (lib/cloudflare/content-encoding.ts).
    return withAcceptedEncoding(
      request,
      await handler.fetch(request, env, ctx),
    );
  },

  async scheduled(
    controller: { cron: string; scheduledTime: number },
    env: Env,
    ctx: Ctx,
  ): Promise<void> {
    const path = CRON_JOBS[controller.cron];

    if (!path) {
      throw new Error(`No job for cron "${controller.cron}"`);
    }
    if (!env.CRON_SECRET) {
      throw new Error(`CRON_SECRET is not set; ${path} would answer 401`);
    }

    // Never leaves the Worker: the request goes straight to the Next handler.
    const response: Response = await handler.fetch(
      new Request(`https://www.hyperwhisper.com${path}`, {
        headers: { authorization: `Bearer ${env.CRON_SECRET}` },
      }),
      env,
      ctx,
    );
    const body = await response.text();

    if (!response.ok) {
      // A thrown error marks the cron invocation failed in Workers Logs.
      throw new Error(`${path} -> ${response.status}: ${body.slice(0, 500)}`);
    }
    // Workers Logs is the only record a cron run leaves.
    // eslint-disable-next-line no-console
    console.log(
      JSON.stringify({
        event: "cron",
        path,
        status: response.status,
        body: body.slice(0, 500),
      }),
    );
  },
};
